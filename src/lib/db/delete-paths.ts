/**
 * 계정 삭제가 닿는 범위. **내보내기 목록의 거울이다** (`export-tables.ts`).
 *
 * `/api/account/delete` 는 표 목록을 돌지 않는다. `users` 행 하나를 지우고 **FK 가 CASCADE 로
 * 흘리게 둔다.** 목록이 없으니 목록 표류도 없어서 내보내기보다 나은 설계다. 하지만 같은 질문이
 * 한 칸 옆으로 옮겨 갔을 뿐이다:
 *
 * > **사용자 행을 가진 표가 전부 `users` 까지 CASCADE 로 이어져 있나?**
 *
 * 안 이어진 표가 하나 생기면 삭제가 그 표의 행을 **조용히 남긴다.** 오류도 안 나고 응답은
 * `{ ok: true }` 다. 그리고 이쪽이 내보내기보다 무겁다 —
 *
 * | | 조용히 틀리면 |
 * | --- | --- |
 * | 내보내기 | 사용자가 **다 가졌다고 믿는데** 안 가졌다 |
 * | 삭제     | 사용자가 **다 지웠다고 믿는데** 안 지워졌다 |
 *
 * `CLAUDE.md` 는 "계정 삭제 시 백업 사본까지 삭제" 라고 적어 뒀고 라우트 주석도 스스로
 * "지웠다고 응답해 놓고 남기지 않는다" 고 말한다. 그 약속이 **가정 위에 서 있다.**
 *
 * ## FK 가 있다는 것과 지워진다는 것은 다르다
 *
 * 이 파일이 붙드는 것은 표의 목록이 아니라 **삭제 규칙**이다. `users` 로 가는 FK 가 있어도
 * 규칙이 `SET NULL` 이면 행은 **살아남는다.** 그리고 이 스키마에서 그건 단순한 잔존이 아니다 —
 * `nodes` · `edges` 는 `user_id` 가 NULL 을 허용하고, **NULL 은 "공용 참조 데이터" 를 뜻한다**
 * (`0001_init.sql:92`). 규칙이 `SET NULL` 로 바뀌면 계정을 지울 때 그 사람의 개인 노드가
 * 주인만 잃고 남아 **모든 계정이 읽는 공용 데이터가 된다** (`0002_rls.sql` 의 `nodes_read`).
 * 남는 것보다 나쁜 새는 것이고, "users 로 가는 FK 가 있나" 만 보는 검사는 이걸 통과시킨다.
 *
 * 그래서 `pnpm test:db` 는 FK 의 **존재가 아니라 규칙**을 견준다
 * (`scripts/test/delete-paths.test.ts`). 차이가 있으면 아래에 **선언된 차이**여야 한다.
 */

