/**
 * 덩어리를 맞춰 보는 **한 가지 방법**. 규칙은 `docs/FLOW.md` 4장에 있다:
 * 소문자 · 앞뒤 공백 제거 · 가운데 공백 하나로 · 앞뒤 문장부호 제거.
 *
 * **왜 한 곳인가.** 같은 덩어리를 새로 만들지 않는 것이 "같은 덩어리 5회차 곡선 일치도"
 * (`docs/SPEC.md` 9장)의 전제다. 맞춰 보는 자리가 둘이 되면 한쪽은 잇고 한쪽은 안 이어서,
 * 같은 말이 1회차짜리 둘로 갈린다. 그러면 그 기준을 **영영 못 잰다.**
 *
 * **접기 하나를 빼면 몇 군데가 무너지나 — 「의존 폭」.** 넷을 하나씩 빼고 `same-chunk.test.ts` 를
 * 돌려 봤다: 소문자 4 · 앞뒤 문장부호 4 · 가운데 공백 3 · 앞뒤 공백 3 (시험 개수). 소문자를 빼면
 * **F14 가리키기·F18 목록·홈 개수·상황 한 줄** 넷이 같이 빨개진다 — 접기 하나가 화면 네 군데를
 * 지고 있다는 뜻이다. **이 수는 "시험이 물리나" 가 아니라 "여기를 만지면 어디까지 가나" 를 말한다.**
 * 다시 재려면 접기를 하나 빼고 그 시험을 돌리면 된다. 넷 다 0 이 아니었다 — 있으나 마나 한 접기는 없다.
 *
 * 그래서 SQL 로 같은 규칙을 한 번 더 적지 않는다 — 후보를 읽어 와 여기서 견준다.
 * 개인 앱이라 한 사람의 한 언어 덩어리가 수천을 넘지 않는다. 값이 커지면 그때 이 함수의 결과를
 * 칸에 적고 색인을 걸면 된다(규칙은 여전히 여기 하나다).
 */
export function chunkKey(s: string): string {
  return s
    .toLowerCase()
    .replace(/\s+/gu, " ")
    .trim()
    .replace(/^\p{P}+|\p{P}+$/gu, "")
    .trim();
}
