/**
 * **「틀」이 무엇인지 한 자리에서 정한다.**
 *
 * 참고 화면의 틀은 폭 390px 짜리 div 하나이고, 높이는 **화면이 제 값을 선언한다** — 대개 844 이고
 * F16 처럼 원래 스크롤되는 화면은 더 크다. `design:lint` 는 이미 그 선언을 읽어서 넘침을 재는데
 * `design:diff` 는 844 를 박아 놓고 거기서 잘랐다. **같은 레포 안에서 「틀」의 뜻이 둘이었다.**
 *
 * 그래서 F16 만 터졌다. 잘리는 것 자체는 문제가 아니다(F03 은 내용이 2,400px 을 넘는데도 0.02% 다).
 * F16 은 `Grow` 로 주 버튼을 **바닥**에 붙이는데 참고의 바닥은 1014, 앱의 바닥은 844 였다 —
 * 844 로 자르면 참고 버튼은 잘려 나가고 앱 버튼은 남는다. **내용으로는 절대 못 줄이는 차이**가
 * 퍼센트로 남아 "볼 차례" 를 거짓으로 만든다. 자가 흐리면 순위가 먼저 거짓이 된다.
 *
 * 두 도구가 여기서 같은 규칙을 읽는다. 틀을 찾는 법이 바뀌면 이 파일만 바뀐다.
 */

/** 참고 화면의 폭. 이것만은 화면이 안 바꾼다 — 틀을 찾는 표식이기도 하다. */
export const FRAME_W = 390;

/** 선언을 안 읽는 자리(전부 이 값을 선언한다)와 "이보다 크면 스크롤" 의 기준. */
export const FRAME_H = 844;

/**
 * 틀을 찾는 규칙: **폭으로 찾는다.** 높이로 찾으면 제 높이를 선언한 화면에서 **빗나가 body 로
 * 떨어지고**, body 는 넘치는 일이 없어 검사가 조용히 통과한다 (`lint-screens.ts` 가 겪은 것).
 *
 * 정규식이 아니라 그 **글자**를 내보내는 이유는 `page.evaluate` 안이 다른 세계라서다 — 함수도
 * 정규식도 안 건너가고 값만 건너간다. 받는 쪽에서 `new RegExp` 로 세운다.
 */
export const FRAME_STYLE = "width:\\s*390px";
